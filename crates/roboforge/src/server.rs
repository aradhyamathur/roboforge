pub fn random_token() -> String {
    use std::io::Read;
    let mut b = [0u8; 16];
    std::fs::File::open("/dev/urandom")
        .and_then(|mut f| f.read_exact(&mut b))
        .expect("cannot read /dev/urandom for the session token");
    b.iter().map(|x| format!("{x:02x}")).collect()
}

pub fn serve(ctx: Arc<Ctx>, listener: TcpListener) {
    for stream in listener.incoming().flatten() {
        let ctx = Arc::clone(&ctx);
        std::thread::spawn(move || handle(&ctx, stream));
    }
}

fn handle(ctx: &Ctx, stream: TcpStream) {
    let _ = stream.set_read_timeout(Some(std::time::Duration::from_secs(30)));
    let Ok(req) = read_request(&stream) else { return };

    // Refuse anything not addressed to loopback (DNS rebinding).
    let host = req.headers.get("host").map(String::as_str).unwrap_or("");
    if host != format!("127.0.0.1:{}", ctx.port) && host != format!("localhost:{}", ctx.port) {
        return respond(&stream, 403, "text/plain", b"forbidden host");
    }
    if req.method == "GET" && (req.path == "/" || req.path == "/index.html") {
        let page = INDEX.replace("__RF_TOKEN__", &ctx.token);
        return respond(&stream, 200, "text/html; charset=utf-8", page.as_bytes());
    }
    if req.method == "GET" && req.path.starts_with("/docs") {
        // Relative links between the two pages resolve under /docs/.
        let page = match req.path.as_str() {
            "/docs" | "/docs/" | "/docs/index.html" => Some(DOCS),
            "/docs/sdk.html" => Some(SDK_DOCS),
            _ => None,
        };
        return match page {
            Some(html) => respond(&stream, 200, "text/html; charset=utf-8", html.replacen("<head>", "<head>\n<base href=\"/docs/\">", 1).as_bytes()),
            None => respond(&stream, 404, "text/plain", b"not found"),
        };
    }
    if !req.path.starts_with("/api/") || req.method != "POST" {
        return respond(&stream, 404, "text/plain", b"not found");
    }
    // The API can run commands, so every call must carry the session token
    // that only the served page knows. Other local web pages cannot read it.
    if req.headers.get("x-rf-token") != Some(&ctx.token) {
        return respond(&stream, 403, "application/json", br#"{"error":"bad session token"}"#);
    }
    let body: Value = if req.body.is_empty() { json!({}) } else {
        match serde_json::from_slice(&req.body) {
            Ok(v) => v,
            Err(e) => return respond_json(&stream, Err(format!("invalid JSON: {e}"))),
        }
    };
    respond_json(&stream, api(ctx, &req, &body));
}

/// rc file for interactive shells: the user's ~/.bashrc, then the project environment.
fn terminal_rc(dir: &Path) -> Result<PathBuf, String> {
    let rc = dir.join(".roboforge").join("terminal-rc.sh");
    let q = |p: &Path| format!("'{}'", p.to_string_lossy().replace('\'', "'\\''"));
    let body = format!("# Generated by RoboForge for its integrated terminals.\n[ -f ~/.bashrc ] && . ~/.bashrc\n. {}\n", q(&dir.join(".roboforge").join("activate.sh")));
    std::fs::write(&rc, body).map_err(|e| format!("{}: {e}", rc.display()))?;
    Ok(rc)
}

