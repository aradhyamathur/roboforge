/// Run install units in order, recording each finished unit so a failed or
/// cancelled install resumes instead of starting over.
pub fn run_units(job: &Job, home: &Home, units: &[Unit]) -> i32 {
    if units.is_empty() {
        job.say("Everything is already installed.");
        return 0;
    }
    let _ = std::fs::create_dir_all(&home.root);
    for (i, u) in units.iter().enumerate() {
        job.say(&format!("\n━━ [{}/{}] {}", i + 1, units.len(), u.label));
        for st in &u.steps {
            job.say(&format!("▶ {}", st.title));
            let code = job.run_shell(&format!("set -e\n{}", st.cmd), &home.root);
            if code != 0 {
                job.say(&format!("\n✖ Failed (exit {code}) in: {}\n  Finished units are kept; run the install again to resume.", st.title));
                return code;
            }
        }
        if let Err(e) = mark_done(home, &u.key) {
            job.say(&format!("✖ cannot write state: {e}"));
            return 1;
        }
    }
    job.say("\n✔ SDKs ready.");
    0
}

fn start_install(ctx: &Ctx, cat: &Catalog, comps: &[String], title: &str) -> Result<Value, String> {
    let res = resolve(cat, comps)?;
    let units = plan(&ctx.home, cat, &res, &State::load(&ctx.home));
    let home = ctx.home.clone();
    let job = ctx.jobs.start(title, move |job| run_units(job, &home, &units));
    Ok(json!({ "job": job.id, "title": job.title }))
}

fn selection(b: &Value) -> Result<Selection, String> {
    Ok(Selection {
        ros: b.get("ros").and_then(Value::as_str).filter(|r| !r.is_empty()).map(String::from),
        modules: str_list(b, "modules")?,
        components: b.get("components").map(|_| str_list(b, "components")).transpose()?.unwrap_or_default(),
        ros_workspace: b.get("ros_workspace").and_then(Value::as_str).map(str::trim).filter(|p| !p.is_empty()).map(String::from),
    })
}

fn project_info(ctx: &Ctx, cat: &Catalog, reg: &Registry, dir: &Path) -> Result<Value, String> {
    let proj = Project::load(dir)?;
    let comps = project_components(cat, reg, &proj);
    let (missing, problem) = match comps.clone().and_then(|c| resolve(cat, &c)) {
        Ok(res) => {
            let _ = write_activation(&ctx.home, cat, dir, &proj, comps.as_deref().unwrap_or(&[]));
            let units = plan(&ctx.home, cat, &res, &State::load(&ctx.home));
            (units.iter().map(|u| u.label.clone()).collect::<Vec<_>>(), None)
        }
        Err(e) => (vec![], Some(e)),
    };
    let comps = comps.unwrap_or_default();
    let ros = comps.iter().filter_map(|c| cat.get(c)).find_map(|c| c.ros_version);
    let workspaces: Vec<Value> = proj
        .workspaces
        .iter()
        .map(|w| {
            let abs = w.abs(dir);
            json!({
                "kind": w.kind, "path": w.path, "abs": abs.to_string_lossy(), "external": w.external(), "exists": abs.is_dir(),
                "packages": if w.is_ros() { json!(ros_packages(&abs)) } else { Value::Null },
            })
        })
        .collect();
    Ok(json!({ "dir": dir.to_string_lossy(), "project": proj, "components": comps, "workspaces": workspaces, "missing": missing, "problem": problem, "ros": ros }))
}

fn api(ctx: &Ctx, req: &Req, b: &Value) -> Result<Value, String> {
    let home = &ctx.home;
    let cat = Catalog::load(home)?;
    let reg = Registry::load(home, &cat)?;
    match req.path.as_str() {
        "/api/boot" => {
            let default_dir = expand_tilde("~/roboforge-projects");
            Ok(json!({
                "version": env!("CARGO_PKG_VERSION"),
                "home": home.root.to_string_lossy(),
                "catalog_override": home.catalog_override().exists(),
                "default_dir": default_dir.to_string_lossy(),
                "catalog": cat,
                "presets": PRESETS,
                "modules": reg.modules.iter().map(|m| &m.def).collect::<Vec<_>>(),
                "modules_dir": home.modules_dir().to_string_lossy(),
                "state": State::load(home),
                "recent": recent(home),
            }))
        }
        "/api/sdk/plan" => {
            let res = resolve(&cat, &str_list(b, "components")?)?;
            let units = plan(home, &cat, &res, &State::load(home));
            Ok(json!({ "resolution": res, "units": units_json(&units) }))
        }
        "/api/project/plan" => {
            let sel = selection(b)?;
            let comps = components_for(&cat, &reg, &sel)?;
            let res = resolve(&cat, &comps)?;
            let units = plan(home, &cat, &res, &State::load(home));
            let mods: Vec<&str> = reg.expand(&sel.modules)?.iter().map(|m| m.def.id.as_str()).collect();
            Ok(json!({ "components": comps, "modules": mods, "resolution": res, "units": units_json(&units) }))
        }
        "/api/project/modules" => {
            let dir = project_dir(b)?;
            let change = set_modules(home, &cat, &reg, &dir, &str_list(b, "modules")?)?;
            let mut info = project_info(ctx, &cat, &reg, &dir)?;
            info["written"] = json!(change.written);
            info["left"] = json!(change.left);
            Ok(info)
        }
        "/api/sdk/install" => start_install(ctx, &cat, &str_list(b, "components")?, "Install SDKs"),
        "/api/sdk/remove" => {
            let mut st = State::load(home);
            if let Some(env) = b.get("env").and_then(Value::as_str) {
                if !st.envs.contains_key(env) {
                    return Err(format!("no such environment: {env}"));
                }
                let _ = std::fs::remove_dir_all(home.env_prefix(env));
                st.envs.remove(env);
            } else {
                let id = s(b, "sdk")?;
                if !st.sdks.contains(id) {
                    return Err(format!("no such SDK: {id}"));
                }
                let _ = std::fs::remove_dir_all(home.sdk_dir(id));
                st.sdks.remove(id);
            }
            st.save(home).map_err(|e| e.to_string())?;
            Ok(json!({ "state": st }))
        }
        "/api/project/new" => {
            let dir = project_dir(b)?;
            // A stack from the picker: validate it before anything is written.
            let stack: Option<roboforge_core::sdk::Stack> = match b.get("sdk").filter(|v| v.is_object()) {
                Some(v) => {
                    let st: roboforge_core::sdk::Stack = serde_json::from_value(v.clone()).map_err(|e| format!("invalid stack: {e}"))?;
                    st.validate()?;
                    Some(st)
                }
                None => None,
            };
            let mut sel = selection(b)?;
            if let Some(st) = &stack {
                for c in st.components() {
                    if !sel.components.contains(&c) {
                        sel.components.push(c);
                    }
                }
            }
            let name = s(b, "name")?;
            generate(home, &cat, &reg, &dir, name, &sel)?;
            if let Some(st) = &stack {
                roboforge_core::sdk::install(home)?;
                let mut proj = Project::load(&dir)?;
                let app = dir.join("app");
                std::fs::create_dir_all(&app).map_err(|e| format!("{}: {e}", app.display()))?;
                for (rel, body) in roboforge_core::sdk::scaffold(&proj.name, st)? {
                    std::fs::write(app.join(&rel), body).map_err(|e| format!("{rel}: {e}"))?;
                }
                if st.cpp() {
                    // clangd (and so VS Code's C++ support) finds the SDK's header from this.
                    let inc = roboforge_core::sdk::dir(home).join("roboforge/cpp/include");
                    let clangd = format!("CompileFlags:\n  Add: [-std=c++17, -I{}]\n", inc.display());
                    std::fs::write(app.join(".clangd"), clangd).map_err(|e| format!(".clangd: {e}"))?;
                }
                proj.workspaces.push(Workspace { kind: "app".into(), path: "app".into() });
                let mut run: Vec<roboforge_core::project::RunConfig> = roboforge_core::sdk::run_configs(st).into_iter()
                    .map(|(name, cmd)| roboforge_core::project::RunConfig { name, cmd, workspace: Some("app".into()), env: None }).collect();
                run.append(&mut proj.run);
                proj.run = run;
                // Use the light SDK environment if it has been set up already.
                let py = roboforge_core::sdk::light_python(home);
                if py.is_file() {
                    proj.setup.python = Some(py.to_string_lossy().to_string());
                }
                proj.save(&dir)?;
            }
            remember(home, &dir);
            project_info(ctx, &cat, &reg, &dir)
        }
        "/api/project/init" => {
            let dir = project_dir(b)?;
            adopt(home, &cat, &reg, &dir, b.get("name").and_then(Value::as_str).unwrap_or(""), s(b, "ros")?)?;
            remember(home, &dir);
            project_info(ctx, &cat, &reg, &dir)
        }
        "/api/sdk/setup" => {
            // Create (or update) the light Python environment for SDK apps and point this project at it.
            let dir = project_dir(b)?;
            Project::load(&dir)?;
            let script = roboforge_core::sdk::light_env_script(home);
            let py = roboforge_core::sdk::light_python(home).to_string_lossy().to_string();
            let sdk_path = roboforge_core::sdk::install(home)?.to_string_lossy().to_string();
            let cwd = dir.clone();
            let job = ctx.jobs.start("SDK environment", move |job| {
                job.say("Setting up the light Python environment for RoboForge SDK apps (system Python + mujoco, pymavlink, gymnasium).");
                let code = job.run_shell(&format!("export PYTHONPATH={}\n{script}", roboforge_core::sh_quote(&sdk_path)), &cwd);
                if code == 0 {
                    match Project::load(&cwd) {
                        Ok(mut p) => {
                            p.setup.python = Some(py.clone());
                            match p.save(&cwd) {
                                Ok(()) => job.say("\nThis project now uses that environment (Environment ▸ Python for builds)."),
                                Err(e) => job.say(&format!("\nCould not update roboforge.json: {e}")),
                            }
                        }
                        Err(e) => job.say(&format!("\nCould not update roboforge.json: {e}")),
                    }
                }
                job.say(&format!("\n[exit {code}]"));
                code
            });
            Ok(json!({ "job": job.id, "title": job.title }))
        }
        "/api/project/stack" => {
            // Components and signal wiring of an SDK app, from the SDK's own `info` command.
            let dir = project_dir(b)?;
            let proj = Project::load(&dir)?;
            write_activation(home, &cat, &dir, &proj, &project_components(&cat, &reg, &proj)?)?;
            let cwd = fs_root(b)?;
            let file = b.get("config").and_then(Value::as_str).unwrap_or("app.yaml");
            if file.contains('/') || file.contains("..") {
                return Err("config must be a file name in the workspace".into());
            }
            let script = wrap(&dir, &format!("python3 -m roboforge info {} --json", roboforge_core::sh_quote(file)), None);
            let out = std::process::Command::new("bash").arg("-c").arg(script).current_dir(&cwd).stdin(std::process::Stdio::null()).output().map_err(|e| e.to_string())?;
            let text = String::from_utf8_lossy(&out.stdout);
            match text.find('{').and_then(|i| serde_json::from_str::<Value>(&text[i..]).ok()) {
                Some(v) if out.status.success() => Ok(v),
                _ => {
                    let err = String::from_utf8_lossy(&out.stderr);
                    let last: Vec<&str> = err.lines().filter(|l| !l.starts_with("roboforge: SDK environment") && !l.trim().is_empty()).collect();
                    Err(format!("Could not read the app.\n{}\nRun \"SDK: check environment\" to see what is missing.", last.iter().rev().take(3).rev().cloned().collect::<Vec<_>>().join("\n")))
                }
            }
        }
        "/api/project/import" => {
            // Android-Studio-style import: the source folder is only read. The RoboForge
            // project (roboforge.json, .roboforge/) is created next to the other projects
            // and points at the source as an external workspace.
            let source = expand_tilde(s(b, "source")?.trim());
            if !source.is_absolute() || !source.is_dir() {
                return Err(format!("{} is not a folder", source.display()));
            }
            let source = source.canonicalize().map_err(|e| e.to_string())?;
            if source.join(MANIFEST).is_file() {
                return Err(format!("{} already is a RoboForge project; open it instead.", source.display()));
            }
            let preview = b.get("preview").and_then(Value::as_bool) == Some(true);
            let name = b.get("name").and_then(Value::as_str).map(str::trim).filter(|n| !n.is_empty()).map(String::from)
                .unwrap_or_else(|| source.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_else(|| "project".into()));
            if name.contains('/') || name.starts_with('.') {
                return Err("the project name cannot contain / or start with a dot".into());
            }
            // A colcon/catkin workspace keeps its ROS kind; anything else is a plain app folder.
            let is_ros = !ros_packages(&source).is_empty();
            let ros = b.get("ros").and_then(Value::as_str).filter(|r| !r.is_empty()).map(String::from).or_else(|| is_ros.then(|| "ros2-jazzy".to_string()));
            let v2 = ros.as_deref().map(|r| !r.starts_with("ros1"));
            let kind = match (is_ros, v2) { (true, Some(false)) => "ros1", (true, _) => "ros2", _ => "app" };
            let base = expand_tilde("~/roboforge-projects");
            let mut target = base.join(&name);
            let mut n = 2;
            while target.join(MANIFEST).is_file() {
                // Importing the same folder again reopens the existing project.
                if Project::load(&target).map_or(false, |p| p.workspaces.iter().any(|w| w.abs(&target) == source)) {
                    if preview {
                        return Ok(json!({ "exists": true, "project_dir": target.to_string_lossy(), "name": name }));
                    }
                    remember(home, &target);
                    return project_info(ctx, &cat, &reg, &target);
                }
                target = base.join(format!("{name}-{n}"));
                n += 1;
            }
            let dir = if preview { home.root.join("run").join(format!("import-preview-{}", ctx.port)) } else { target.clone() };
            let rc = |name: &str, cmd: &str| roboforge_core::project::RunConfig { name: name.into(), cmd: cmd.into(), workspace: Some(kind.into()), env: None };
            let mut proj = Project {
                name: name.clone(),
                ros: ros.clone().filter(|_| is_ros || b.get("ros").is_some()),
                workspaces: vec![Workspace { kind: kind.into(), path: source.to_string_lossy().to_string() }],
                env: roboforge_core::templates::default_env(if is_ros { Some(if kind == "ros1" { 1 } else { 2 }) } else { None }),
                run: match kind {
                    "ros2" => vec![rc("Build workspace (colcon)", "colcon build --symlink-install"), rc("Test (colcon)", "colcon test && colcon test-result --verbose")],
                    "ros1" => vec![rc("Build workspace (catkin)", "catkin_make")],
                    _ => vec![],
                },
                ..Default::default()
            };
            std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
            proj.save(&dir)?;
            let comps = project_components(&cat, &reg, &proj)?;
            write_activation(home, &cat, &dir, &proj, &comps)?;
            // First scan finds the interpreter; apply it, then scan again in the final environment.
            let scan = roboforge_core::tools::scan(&dir, &proj, &project_env(&dir)?);
            if let Some(st) = &scan.suggested_setup {
                proj.setup = st.clone();
                proj.save(&dir)?;
                write_activation(home, &cat, &dir, &proj, &comps)?;
            }
            let scan = roboforge_core::tools::scan(&dir, &proj, &project_env(&dir)?);
            proj.launch = Some(scan.suggested.clone());
            // Tests and docs become run configurations of non-ROS projects.
            if kind == "app" {
                for t in scan.tools.iter().filter(|t| t.primary && (t.role == "test" || t.role == "docs") && t.args.is_empty()) {
                    proj.run.push(roboforge_core::project::RunConfig { name: t.name.clone(), cmd: t.cmd.clone(), workspace: t.workspace.clone(), env: None });
                }
            }
            proj.save(&dir)?;
            let mut roles: Vec<(String, usize)> = Vec::new();
            for t in scan.tools.iter().filter(|t| !t.helper) {
                match roles.iter_mut().find(|(r, _)| *r == t.role) {
                    Some(e) => e.1 += 1,
                    None => roles.push((t.role.clone(), 1)),
                }
            }
            let report = json!({
                "name": name, "source": source.to_string_lossy(), "project_dir": target.to_string_lossy(), "kind": scan.kind, "ros": proj.ros,
                "summary": scan.summary, "notes": scan.notes, "python": proj.setup.python, "launch": proj.launch, "run": proj.run,
                "roles": roles.iter().map(|(r, n)| json!({ "role": r, "count": n })).collect::<Vec<_>>(),
                "env": scan.env,
            });
            if preview {
                let _ = std::fs::remove_dir_all(&dir);
                return Ok(report);
            }
            remember(home, &dir);
            let mut info = project_info(ctx, &cat, &reg, &dir)?;
            info["import"] = report;
            Ok(info)
        }
        "/api/project/workspaces" => {
            let dir = project_dir(b)?;
            let list: Vec<Workspace> = serde_json::from_value(b.get("workspaces").cloned().unwrap_or(json!([]))).map_err(|e| format!("workspaces: {e}"))?;
            set_workspaces(home, &cat, &reg, &dir, &list)?;
            project_info(ctx, &cat, &reg, &dir)
        }
        "/api/project/package" => {
            let dir = project_dir(b)?;
            let ws = b.get("ws").and_then(Value::as_u64).unwrap_or(0) as usize;
            let written = new_package(&dir, ws, s(b, "name")?, b.get("kind").and_then(Value::as_str).unwrap_or("ament_python"))?;
            let mut info = project_info(ctx, &cat, &reg, &dir)?;
            info["written"] = json!(written);
            Ok(info)
        }
        "/api/project/open" => {
            let dir = project_dir(b)?;
            let info = project_info(ctx, &cat, &reg, &dir)?;
            remember(home, &dir);
            Ok(info)
        }
        "/api/project/sync" => {
            let dir = project_dir(b)?;
            let proj = Project::load(&dir)?;
            let comps = project_components(&cat, &reg, &proj)?;
            write_activation(home, &cat, &dir, &proj, &comps)?;
            start_install(ctx, &cat, &comps, "Sync SDKs")
        }
        "/api/fs/list" => {
            let dir = safe_join(&fs_root(b)?, b.get("path").and_then(Value::as_str).unwrap_or(""))?;
            let mut entries: Vec<(bool, String)> = std::fs::read_dir(&dir)
                .map_err(|e| format!("{}: {e}", dir.display()))?
                .flatten()
                .map(|e| (e.path().is_dir(), e.file_name().to_string_lossy().to_string()))
                .filter(|(_, n)| n != ".git" && n != "__pycache__")
                .collect();
            entries.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.to_lowercase().cmp(&b.1.to_lowercase())));
            entries.truncate(2000);
            Ok(json!({ "entries": entries.iter().map(|(d, n)| json!({"name": n, "dir": d})).collect::<Vec<_>>() }))
        }
        "/api/fs/read" => {
            let f = safe_join(&fs_root(b)?, s(b, "path")?)?;
            let meta = std::fs::metadata(&f).map_err(|e| format!("{}: {e}", f.display()))?;
            if meta.len() > 4 << 20 {
                return Err("file is larger than 4 MB".into());
            }
            let bytes = std::fs::read(&f).map_err(|e| e.to_string())?;
            let text = String::from_utf8(bytes).map_err(|_| "not a UTF-8 text file".to_string())?;
            Ok(json!({ "text": text }))
        }
        "/api/fs/write" => {
            let project = project_dir(b)?;
            let root = fs_root(b)?;
            let rel = s(b, "path")?;
            let f = safe_join(&root, rel)?;
            if let Some(p) = f.parent() {
                std::fs::create_dir_all(p).map_err(|e| e.to_string())?;
            }
            if b.get("create").and_then(Value::as_bool) == Some(true) && f.exists() {
                return Err(format!("{rel} already exists"));
            }
            std::fs::write(&f, s(b, "text")?).map_err(|e| format!("{}: {e}", f.display()))?;
            if rel == MANIFEST && root == project {
                let info = project_info(ctx, &cat, &reg, &project)?;
                refresh_code_workspace(&project);
                return Ok(info);
            }
            Ok(json!({}))
        }
        "/api/run" => {
            let dir = project_dir(b)?;
            let proj = Project::load(&dir)?;
            write_activation(home, &cat, &dir, &proj, &project_components(&cat, &reg, &proj)?)?;
            let (title, cmd, env, cwd) = match b.get("config").and_then(Value::as_str) {
                Some(name) => {
                    let rc = proj.run.iter().find(|r| r.name == name).ok_or_else(|| format!("no run configuration named {name}"))?;
                    (rc.name.clone(), rc.cmd.clone(), rc.env.clone(), proj.run_dir(&dir, rc))
                }
                None => {
                    let cmd = s(b, "cmd")?.to_string();
                    let cwd = b.get("workspace").and_then(Value::as_str).and_then(|k| proj.workspace(k)).map(|w| w.abs(&dir)).unwrap_or_else(|| dir.clone());
                    let title = b.get("title").and_then(Value::as_str).map(String::from).unwrap_or_else(|| cmd.chars().take(40).collect());
                    (title, cmd, b.get("env").and_then(Value::as_str).map(String::from), cwd)
                }
            };
            std::fs::create_dir_all(&cwd).map_err(|e| format!("{}: {e}", cwd.display()))?;
            let script = wrap(&dir, &cmd, env.as_deref());
            let shown = if cwd == dir { String::new() } else { format!("  (in {})", cwd.display()) };
            let job = ctx.jobs.start(&title, move |job| {
                job.say(&format!("$ {cmd}{shown}"));
                let code = job.run_shell(&script, &cwd);
                job.say(&format!("\n[exit {code}]"));
                code
            });
            Ok(json!({ "job": job.id, "title": job.title }))
        }
        "/api/job/poll" => {
            let id = b.get("id").and_then(Value::as_u64).ok_or("missing field: id")?;
            let job = ctx.jobs.get(id).ok_or("no such job")?;
            let (data, offset) = job.read_from(b.get("offset").and_then(Value::as_u64).unwrap_or(0));
            let (running, code) = match job.status() {
                Status::Running => (true, Value::Null),
                Status::Done(c) => (false, json!(c)),
            };
            Ok(json!({ "data": data, "offset": offset, "running": running, "code": code }))
        }
        "/api/job/kill" => {
            let id = b.get("id").and_then(Value::as_u64).ok_or("missing field: id")?;
            let job = ctx.jobs.get(id).ok_or("no such job")?;
            job.kill();
            if b.get("forget").and_then(Value::as_bool) == Some(true) {
                ctx.jobs.forget(id);
            }
            Ok(json!({}))
        }
        "/api/project/tools" => {
            let dir = project_dir(b)?;
            let proj = Project::load(&dir)?;
            write_activation(home, &cat, &dir, &proj, &project_components(&cat, &reg, &proj)?)?;
            // One activation: capture the project environment, then inspect the tree against it.
            let env = project_env(&dir)?;
            let scan = roboforge_core::tools::scan(&dir, &proj, &env);
            let display = std::env::var_os("DISPLAY").is_some() || std::env::var_os("WAYLAND_DISPLAY").is_some();
            let mut v = serde_json::to_value(&scan).map_err(|e| e.to_string())?;
            v["display"] = json!(display);
            // First look at a project: keep the suggested stack as its initial launch configuration.
            if b.get("init").and_then(Value::as_bool) == Some(true) && proj.launch.is_none() {
                let mut proj = proj;
                proj.launch = Some(scan.suggested.clone());
                if proj.setup.is_empty() {
                    if let Some(st) = &scan.suggested_setup {
                        proj.setup = st.clone();
                    }
                }
                proj.save(&dir)?;
                v["created"] = json!(scan.suggested.first().map(|c| c.name.clone()));
                v["project"] = project_info(ctx, &cat, &reg, &dir)?;
            }
            refresh_code_workspace(&dir);
            Ok(v)
        }
        "/api/project/launch" => {
            let dir = project_dir(b)?;
            let mut proj = Project::load(&dir)?;
            let list: Vec<roboforge_core::project::LaunchConfig> = serde_json::from_value(b.get("launch").cloned().unwrap_or(Value::Null)).map_err(|e| format!("invalid launch configurations: {e}"))?;
            let mut names = std::collections::HashSet::new();
            for c in &list {
                if c.name.trim().is_empty() {
                    return Err("every launch configuration needs a name".into());
                }
                if !names.insert(c.name.trim().to_string()) {
                    return Err(format!("two launch configurations are named {:?}", c.name.trim()));
                }
                if let Some(st) = c.steps.iter().find(|st| st.cmd.trim().is_empty()) {
                    return Err(format!("step {:?} in {:?} has no command", st.name, c.name));
                }
            }
            proj.launch = Some(list);
            proj.save(&dir)?;
            let info = project_info(ctx, &cat, &reg, &dir)?; // rewrites the activation script
            refresh_code_workspace(&dir);
            Ok(info)
        }
        "/api/project/setup" => {
            let dir = project_dir(b)?;
            let mut proj = Project::load(&dir)?;
            proj.setup = serde_json::from_value(b.get("setup").cloned().unwrap_or_else(|| json!({}))).map_err(|e| format!("invalid setup: {e}"))?;
            if let Some(env) = b.get("env").and_then(Value::as_object) {
                let mut out = std::collections::BTreeMap::new();
                for (k, v) in env {
                    if k.is_empty() || !k.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') || k.chars().next().map_or(true, |c| c.is_ascii_digit()) {
                        return Err(format!("{k:?} is not a valid variable name"));
                    }
                    out.insert(k.clone(), v.as_str().unwrap_or_default().to_string());
                }
                proj.env = out;
            }
            proj.save(&dir)?;
            let info = project_info(ctx, &cat, &reg, &dir)?; // rewrites the activation script
            refresh_code_workspace(&dir);
            Ok(info)
        }
        "/api/project/env" => {
            let dir = project_dir(b)?;
            let mut proj = Project::load(&dir)?;
            let name = s(b, "name")?;
            if name.is_empty() || !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
                return Err("invalid variable name".into());
            }
            match b.get("value").and_then(Value::as_str).filter(|v| !v.is_empty()) {
                Some(v) => { proj.env.insert(name.to_string(), v.to_string()); }
                None => { proj.env.remove(name); }
            }
            proj.save(&dir)?;
            let info = project_info(ctx, &cat, &reg, &dir)?; // rewrites the activation script
            refresh_code_workspace(&dir);
            Ok(info)
        }
        "/api/vscode/start" => {
            // VS Code's own local web server (`code serve-web`), started inside the project
            // environment so its terminals, tasks and language servers see ROS and the overlays.
            let dir = project_dir(b)?;
            let proj = Project::load(&dir)?;
            write_activation(home, &cat, &dir, &proj, &project_components(&cat, &reg, &proj)?)?;
            let env = project_env(&dir)?;
            let scan = roboforge_core::tools::scan(&dir, &proj, &env);
            code_workspace(&dir, &proj, &env, &scan)?;
            let mut slot = ctx.vscode.lock().unwrap();
            if let Some((job, port, token, started_for)) = slot.clone() {
                let alive = ctx.jobs.get(job).map_or(false, |j| j.status() == Status::Running);
                if alive && started_for == dir {
                    return Ok(json!({ "url": vscode_url(port, &token, &dir), "job": job, "title": "VS Code server", "reused": true }));
                }
                if let Some(j) = ctx.jobs.get(job) {
                    j.kill();
                }
                *slot = None;
            }
            // VS Code keeps workspace trust, layout and sign-ins per address, so each project
            // gets the same port every time (derived from its path); any free one if that is taken.
            let preferred = 20000 + (dir.to_string_lossy().bytes().fold(5381u32, |h, b| h.wrapping_mul(33) ^ b as u32) % 20000) as u16;
            let port = TcpListener::bind(("127.0.0.1", preferred)).or_else(|_| TcpListener::bind(("127.0.0.1", 0))).and_then(|l| l.local_addr()).map_err(|e| e.to_string())?.port();
            let token = random_token();
            let run = home.root.join("run");
            std::fs::create_dir_all(&run).map_err(|e| format!("{}: {e}", run.display()))?;
            let token_file = run.join(format!("vscode-token-{}", ctx.port)); // per instance, so several IDEs can run side by side
            {
                use std::os::unix::fs::OpenOptionsExt;
                use std::io::Write;
                let mut f = std::fs::OpenOptions::new().write(true).create(true).truncate(true).mode(0o600).open(&token_file).map_err(|e| format!("{}: {e}", token_file.display()))?;
                f.write_all(token.as_bytes()).map_err(|e| e.to_string())?;
            }
            let cmd = format!(
                "command -v code >/dev/null || {{ echo 'VS Code (the `code` command) was not found. Install VS Code, or add it to PATH under Environment.'; exit 127; }}\nexec code serve-web --host 127.0.0.1 --port {port} --connection-token-file {} --accept-server-license-terms",
                roboforge_core::sh_quote(&token_file.to_string_lossy())
            );
            let script = wrap(&dir, &cmd, None);
            let cwd = dir.clone();
            let job = ctx.jobs.start("VS Code server", move |job| {
                job.say("$ code serve-web  (VS Code in the editor area; stopping this job closes it)");
                let code = job.run_shell(&script, &cwd);
                job.say(&format!("\n[exit {code}]"));
                code
            });
            // Wait until it listens (or has already failed).
            let deadline = std::time::Instant::now() + std::time::Duration::from_secs(20);
            let mut up = false;
            while std::time::Instant::now() < deadline && job.status() == Status::Running {
                if TcpStream::connect_timeout(&([127, 0, 0, 1], port).into(), std::time::Duration::from_millis(200)).is_ok() {
                    up = true;
                    break;
                }
                std::thread::sleep(std::time::Duration::from_millis(150));
            }
            if !up {
                let (log, _) = job.read_from(0);
                return Err(format!("VS Code server did not start.\n{}", log.trim()));
            }
            *slot = Some((job.id, port, token.clone(), dir.clone()));
            Ok(json!({ "url": vscode_url(port, &token, &dir), "job": job.id, "title": job.title, "reused": false }))
        }
        "/api/term/new" => {
            let dir = project_dir(b)?;
            let proj = Project::load(&dir)?;
            write_activation(home, &cat, &dir, &proj, &project_components(&cat, &reg, &proj)?)?;
            let cwd = fs_root(b)?;
            std::fs::create_dir_all(&cwd).map_err(|e| format!("{}: {e}", cwd.display()))?;
            let rc = terminal_rc(&dir)?;
            let n = |k: &str, d: u64| b.get(k).and_then(Value::as_u64).filter(|v| (1..=1000).contains(v)).unwrap_or(d) as u16;
            let t = ctx.terms.open(&cwd, &rc, n("cols", 80), n("rows", 24))?;
            Ok(json!({ "term": t.id }))
        }
        "/api/term/poll" => {
            let id = b.get("id").and_then(Value::as_u64).ok_or("missing field: id")?;
            let t = ctx.terms.get(id).ok_or("no such terminal")?;
            let (data, offset) = t.read_from(b.get("offset").and_then(Value::as_u64).unwrap_or(0));
            let (alive, code) = t.status();
            Ok(json!({ "data": data, "offset": offset, "alive": alive, "code": code }))
        }
        "/api/term/write" => {
            let id = b.get("id").and_then(Value::as_u64).ok_or("missing field: id")?;
            let t = ctx.terms.get(id).ok_or("no such terminal")?;
            t.write(s(b, "data")?.as_bytes()).map_err(|e| e.to_string())?;
            Ok(json!({}))
        }
        "/api/term/resize" => {
            let id = b.get("id").and_then(Value::as_u64).ok_or("missing field: id")?;
            let t = ctx.terms.get(id).ok_or("no such terminal")?;
            let n = |k: &str| b.get(k).and_then(Value::as_u64).filter(|v| (1..=1000).contains(v)).unwrap_or(24) as u16;
            t.resize(n("cols"), n("rows"));
            Ok(json!({}))
        }
        "/api/term/close" => {
            let id = b.get("id").and_then(Value::as_u64).ok_or("missing field: id")?;
            ctx.terms.close(id);
            Ok(json!({}))
        }
        other => Err(format!("unknown endpoint {other}")),
    }
}
